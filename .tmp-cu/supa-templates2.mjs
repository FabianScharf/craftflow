import puppeteer from 'puppeteer-core'
const browser = await puppeteer.connect({ browserURL: 'http://localhost:9222', defaultViewport: null, protocolTimeout: 120000 })
const page = (await browser.pages()).find(p => p.url().includes('auth/templates')) || await browser.newPage()
if (!page.url().includes('auth/templates')) await page.goto('https://supabase.com/dashboard/project/fepfjvixfxksvduzwsgq/auth/templates', { waitUntil: 'networkidle2', timeout: 90000 })
await new Promise(r => setTimeout(r, 6000))
console.log('URL:', page.url())
const t = await page.evaluate(() => document.body.innerText)
console.log(t.slice(0, 2500))
await page.screenshot({ path: '/tmp/cfshots/supa-templates.png', fullPage: true })
browser.disconnect()
